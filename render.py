# Accented or curly characters fall back to their plain twin.
FALLBACK = {
    "’": "'", "‘": "'", "“": '"', "”": '"', "–": "-",
    "é": "e", "è": "e", "ê": "e", "ë": "e", "á": "a", "à": "a", "ä": "a",
    "ö": "o", "ü": "u", "ï": "i", "ç": "c", "ñ": "n", "ß": "s",
}

BLANK = ("00000000",) * 8


def glyph(ch):
    if ch in FONT:
        return FONT[ch]
    if ch in FALLBACK:
        return FONT[FALLBACK[ch]]
    return BLANK


# --------------------------------------------------------------- canvas ----
class Canvas:
    """A palette image: pixels are one byte each, an index into palette."""

    def __init__(self, width, height, bg):
        self.w = width
        self.h = height
        self.palette = [bg]
        self.index = {bg: 0}
        self.px = bytearray(width * height)

    def color(self, rgb):
        idx = self.index.get(rgb)
        if idx is None:
            if len(self.palette) >= 256:
                raise ValueError("palette full")
            idx = len(self.palette)
            self.palette.append(rgb)
            self.index[rgb] = idx
        return idx

    def set(self, x, y, ci):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y * self.w + x] = ci

    def fill(self, ci):
        self.px = bytearray([ci]) * (self.w * self.h)

    def fill_rect(self, x, y, w, h, ci):
        x0 = max(0, x)
        y0 = max(0, y)
        x1 = min(self.w, x + w)
        y1 = min(self.h, y + h)
        for yy in range(y0, y1):
            base = yy * self.w
            for xx in range(x0, x1):
                self.px[base + xx] = ci

    def hline(self, x, y, w, ci):
        self.fill_rect(x, y, w, 1, ci)

    def vline(self, x, y, h, ci):
        self.fill_rect(x, y, 1, h, ci)

    def rect(self, x, y, w, h, ci, t=1):
        self.fill_rect(x, y, w, t, ci)
        self.fill_rect(x, y + h - t, w, t, ci)
        self.fill_rect(x, y, t, h, ci)
        self.fill_rect(x + w - t, y, t, h, ci)

    def line(self, x0, y0, x1, y1, ci):
        dx = abs(x1 - x0)
        dy = -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            self.set(x0, y0, ci)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def dashed_line(self, x0, y0, x1, y1, ci, dash=6, gap=4):
        length = int(math.hypot(x1 - x0, y1 - y0))
        if length == 0:
            return
        step = dash + gap
        done = 0
        while done < length:
            a = done / length
            b = min(length, done + dash) / length
            self.line(
                int(round(x0 + (x1 - x0) * a)), int(round(y0 + (y1 - y0) * a)),
                int(round(x0 + (x1 - x0) * b)), int(round(y0 + (y1 - y0) * b)),
                ci,
            )
            done += step

    def circle(self, cx, cy, r, ci, fill=True):
        if r <= 0:
            return
        if fill:
            for dy in range(-r, r + 1):
                dx = int(math.sqrt(r * r - dy * dy))
                self.hline(cx - dx, cy + dy, 2 * dx + 1, ci)
        else:
            steps = max(8, int(2 * math.pi * r))
            for i in range(steps):
                a = 2 * math.pi * i / steps
                self.set(int(round(cx + r * math.cos(a))), int(round(cy + r * math.sin(a))), ci)

    def ring(self, cx, cy, r, ci, t=2):
        for rr in range(r - t + 1, r + 1):
            self.circle(cx, cy, rr, ci, fill=False)

    def ellipse(self, cx, cy, rx, ry, ci):
        for dy in range(-ry, ry + 1):
            dx = int(rx * math.sqrt(max(0.0, 1.0 - (dy * dy) / float(ry * ry))))
            self.hline(cx - dx, cy + dy, 2 * dx + 1, ci)

    def poly(self, points, ci):
        """Scanline fill of a simple polygon given as [(x, y), ...]."""
        if len(points) < 3:
            return
        ys = [p[1] for p in points]
        for y in range(max(0, min(ys)), min(self.h, max(ys) + 1)):
            xs = []
            n = len(points)
            for i in range(n):
                x0, y0 = points[i]
                x1, y1 = points[(i + 1) % n]
                if (y0 <= y < y1) or (y1 <= y < y0):
                    xs.append(x0 + (y - y0) * (x1 - x0) / (y1 - y0))
            xs.sort()
            for i in range(0, len(xs) - 1, 2):
                self.hline(int(math.ceil(xs[i])), y, int(math.floor(xs[i + 1])) - int(math.ceil(xs[i])) + 1, ci)

    def burst(self, cx, cy, r, ci):
        """A starburst: filled circle plus eight spikes."""
        self.circle(cx, cy, max(2, r // 2), ci)
        for k in range(8):
            a = math.pi * k / 4.0
            self.line(cx, cy, int(round(cx + r * math.cos(a))), int(round(cy + r * math.sin(a))), ci)
            self.line(cx, cy, int(round(cx + (r * 0.6) * math.cos(a + 0.35))), int(round(cy + (r * 0.6) * math.sin(a + 0.35))), ci)

    # ------------------------------------------------------------ text -----
    def text_w(self, s, scale, advance=None):
        adv = advance if advance is not None else 8 * scale
        return len(s) * adv

    def text(self, x, y, s, scale, ci, bold=False, align="left", advance=None):
        adv = advance if advance is not None else 8 * scale
        if align == "center":
            x -= self.text_w(s, scale, adv) // 2
        elif align == "right":
            x -= self.text_w(s, scale, adv)
        for ch in s:
            g = glyph(ch)
            for row in range(8):
                bits = g[row]
                for col in range(8):
                    if bits[col] == "1":
                        for dy in range(scale):
                            for dx in range(scale):
                                self.set(x + col * scale + dx, y + row * scale + dy, ci)
                                if bold:
                                    self.set(x + col * scale + dx + 1, y + row * scale + dy, ci)
            x += adv
        return x

    def wrap(self, s, max_w, scale, advance=None):
        adv = advance if advance is not None else 8 * scale
        lines = []
        for chunk in s.split("\n"):
            words = chunk.split(" ")
            cur = ""
            for w in words:
                trial = (cur + " " + w).strip()
                if self.text_w(trial, scale, adv) <= max_w or not cur:
                    cur = trial
                else:
                    lines.append(cur)
                    cur = w
            if cur:
                lines.append(cur)
        return lines

    def para(self, x, y, s, scale, ci, max_w, leading, bold=False, advance=None):
        lines = self.wrap(s, max_w, scale, advance)
        for i, ln in enumerate(lines):
            self.text(x, y + i * leading, ln, scale, ci, bold=bold, advance=advance)
        return len(lines) * leading


# ----------------------------------------------------------------- png -----
def _chunk(kind, data):
    out = struct.pack(">I", len(data)) + kind + data
    out += struct.pack(">I", binascii.crc32(kind + data) & 0xFFFFFFFF)
    return out


def _paeth(a, b, c):
    p = a + b - c
    pa = abs(p - a)
    pb = abs(p - b)
    pc = abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def _filter_row(kind, row, prev, bpp=1):
    out = bytearray(len(row))
    if kind == 0:
        out[:] = row
    elif kind == 1:
        for i, v in enumerate(row):
            left = row[i - bpp] if i >= bpp else 0
            out[i] = (v - left) & 0xFF
    elif kind == 2:
        for i, v in enumerate(row):
            out[i] = (v - prev[i]) & 0xFF
    elif kind == 3:
        for i, v in enumerate(row):
            left = row[i - bpp] if i >= bpp else 0
            out[i] = (v - ((left + prev[i]) >> 1)) & 0xFF
    else:
        for i, v in enumerate(row):
            left = row[i - bpp] if i >= bpp else 0
            upleft = prev[i - bpp] if i >= bpp else 0
            out[i] = (v - _paeth(left, prev[i], upleft)) & 0xFF
    return bytes(out)


def write_png(cv, path):
    """Write the canvas as a palette PNG. Deterministic: no time chunks,
    fixed filter choice per row, zlib level 9."""
    if len(cv.palette) > 256:
        raise ValueError("palette over 256 colours")
    plte = b"".join(bytes(rgb) for rgb in cv.palette)
    ihdr = struct.pack(">IIBBBBB", cv.w, cv.h, 8, 3, 0, 0, 0)
    raw = bytearray()
    prev = bytes(cv.w)
    for y in range(cv.h):
        row = bytes(cv.px[y * cv.w:(y + 1) * cv.w])
        best = None
        best_cost = None
        for kind in range(5):
            f = _filter_row(kind, row, prev)
            cost = sum(abs(b if b < 128 else b - 256) for b in f)
            if best_cost is None or cost < best_cost:
                best_cost = cost
                best = (kind, f)
        raw.append(best[0])
        raw.extend(best[1])
        prev = row
    data = (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", ihdr)
        + _chunk(b"PLTE", plte)
        + _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + _chunk(b"IEND", b"")
    )
    with open(path, "wb") as fh:
        fh.write(data)
    return len(data)
